/** 從全部台詞中隨機抽一句 */
export function pickRandomTip() {
  const all = COMPANION_TIPS.flatMap(g => g.lines);
  if (all.length === 0) return '今天也要加油喔！';
  return all[Math.floor(Math.random() * all.length)];
}

/** 依分類抽（找不到分類就退回隨機） */
export function pickTipByCat(cat) {
  const group = COMPANION_TIPS.find(g => g.cat === cat);
  if (!group?.lines?.length) return pickRandomTip();
  return group.lines[Math.floor(Math.random() * group.lines.length)];
}
